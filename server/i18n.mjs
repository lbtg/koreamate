// A couple of messages are built at runtime, so they are matched by shape.
const PATTERNS = [
  [
    /^请输入 (-?\d+) 至 (-?\d+) 的整数$/,
    (m) => `${m[1]} 이상 ${m[2]} 이하의 정수를 입력해 주세요`,
  ],
];

export function translate(message, lang) {
  if (lang !== "ko") return message;
  const exact = KO[message];
  if (exact) return exact;
  for (const [re, build] of PATTERNS) {
    const m = re.exec(message);
    if (m) return build(m);
  }
  return message;
}

// Clients send their language on every request; anything unexpected reads as Chinese.
export const langOf = (req) =>
  String(req.headers["x-lang"] || "").toLowerCase() === "ko" ? "ko" : "zh";
