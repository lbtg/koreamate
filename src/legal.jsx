export function LegalPage({ route, navigate, t }) {
  const page = LEGAL[route];
  useEffect(() => {
    window.scrollTo(0, 0);
  }, [route]);
  if (!page) return null;
  return (
    <div className="page legal">
      <div className="legal-head">
        <h1>{t(...page.title)}</h1>
        <p className="muted">{t(...page.subtitle)}</p>
      </div>
      <article className="panel legal-body">
        {page.sections.map((section) => (
          <section key={section.heading[0]}>
            <h2>{t(...section.heading)}</h2>
            {section.blocks.map((block, i) =>
              block.type === "list" ? (
                <ul key={i}>
                  {block.items.map((item) => (
                    <li key={item[0]}>{t(...item)}</li>
                  ))}
                </ul>
              ) : block.type === "note" ? (
                <p key={i} className="legal-note">
                  {t(...block.text)}
                </p>
              ) : (
                <p key={i}>{t(...block.text)}</p>
              ),
            )}
          </section>
        ))}
      </article>
      <div className="legal-links">
        {Object.entries(LEGAL)
          .filter(([path]) => path !== route)
          .map(([path, other]) => (
            <button
              key={path}
              className="text-button"
              onClick={() => navigate(path)}
            >
              {t(...other.title)}
            </button>
          ))}
        <button className="text-button" onClick={() => navigate("/")}>
          {t("返回首页", "홈으로")}
        </button>
      </div>
    </div>
  );
}
